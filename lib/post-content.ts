import sanitizeHtml from "sanitize-html";

export function sanitizePostContent(content: string): string {
  return sanitizeHtml(content, {
    allowedTags: [
      "a",
      "b",
      "blockquote",
      "br",
      "caption",
      "code",
      "dd",
      "div",
      "dl",
      "dt",
      "em",
      "figcaption",
      "figure",
      "h1",
      "h2",
      "h3",
      "h4",
      "hr",
      "i",
      "img",
      "li",
      "mark",
      "ol",
      "p",
      "pre",
      "s",
      "span",
      "strong",
      "sub",
      "sup",
      "table",
      "tbody",
      "td",
      "th",
      "thead",
      "tr",
      "u",
      "ul",
    ],
    allowedAttributes: {
      a: ["href", "title"],
      img: ["src", "alt", "title", "width", "height"],
      ol: ["start"],
      td: ["colspan", "rowspan"],
      th: ["colspan", "rowspan"],
      span: ["style"],
    },
    allowedStyles: {
      span: {
        "background-color": [/^(?:#[\da-f]{3,8}|rgb\(\s*[\d\s,%]+\))$/i],
        color: [/^(?:#[\da-f]{3,8}|rgb\(\s*[\d\s,%]+\))$/i],
      },
    },
    allowedSchemes: ["http", "https", "mailto"],
    allowedSchemesByTag: { img: ["http", "https"] },
    allowProtocolRelative: false,
  });
}
